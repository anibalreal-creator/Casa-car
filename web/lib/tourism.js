export function tourismText(language = 'es', key = '') {
  return TEXTS[language]?.[key] || TEXTS.es[key] || TEXTS.en[key] || key;
}

export function getTourismSpecs(item = {}) {
  return item?.specs_json && typeof item.specs_json === 'object' ? item.specs_json : {};
}

export function isTruthy(value) {
  return value === true || value === 'true' || value === 1 || value === '1' || value === 'Si' || value === 'Sí';
}

export function isTourismListing(item = {}) {
  const category = String(item?.category || '').toLowerCase();
  const subtype = String(item?.subtype || '').toLowerCase();
  const type = String(item?.listing_type || '').toLowerCase();
  return category.includes('turismo') || type.includes('temporal') || ['hotel', 'cabana', 'cabaña', 'experiencia', 'alquiler temporal'].some((value) => subtype.includes(value));
}

export function splitDates(value = '') {
  return String(value || '')
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean);
}

export function calculateNights(checkIn, checkOut) {
  if (!checkIn || !checkOut) return 0;
  const start = new Date(`${checkIn}T12:00:00`);
  const end = new Date(`${checkOut}T12:00:00`);
  const diff = Math.round((end - start) / 86400000);
  return diff > 0 ? diff : 0;
}

export function hasBlockedDates(specs = {}, checkIn, checkOut) {
  const blocked = new Set(splitDates(specs.blocked_dates));
  const nights = calculateNights(checkIn, checkOut);
  if (!nights) return false;
  const cursor = new Date(`${checkIn}T12:00:00`);
  for (let i = 0; i < nights; i += 1) {
    const iso = cursor.toISOString().slice(0, 10);
    if (blocked.has(iso)) return true;
    cursor.setDate(cursor.getDate() + 1);
  }
  return false;
}

function toNumber(value, fallback = 0) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

export function calculateTourismQuote(item = {}, { checkIn, checkOut, guests = 1 } = {}) {
  const specs = getTourismSpecs(item);
  const nights = calculateNights(checkIn, checkOut);
  const baseNight = toNumber(specs.base_price_night || specs.price_per_night || item.price, 0);
  const weekendNight = toNumber(specs.weekend_price || specs.weekend_night, baseNight);
  const perPerson = toNumber(specs.price_per_person, 0);
  const discount = Math.max(0, Math.min(80, toNumber(specs.weekly_discount, 0)));
  const blocked = hasBlockedDates(specs, checkIn, checkOut);

  let total = 0;
  if (nights > 0) {
    const cursor = new Date(`${checkIn}T12:00:00`);
    for (let i = 0; i < nights; i += 1) {
      const day = cursor.getDay();
      total += day === 5 || day === 6 ? weekendNight : baseNight;
      cursor.setDate(cursor.getDate() + 1);
    }
    total += perPerson * Math.max(0, toNumber(guests, 1) - 1) * nights;
    if (nights >= 7 && discount) total -= total * (discount / 100);
  }

  return {
    nights,
    total: Math.max(0, Math.round(total)),
    blocked,
    currency: item.currency || 'USD',
  };
}

export function getAmenityLabels(item = {}, language = 'es') {
  const specs = getTourismSpecs(item);
  return TOURISM_AMENITIES
    .filter((key) => isTruthy(specs[key]) || (key === 'pool' && isTruthy(item.pool)) || (key === 'parking' && isTruthy(item.garage)))
    .map((key) => tourismText(language, key));
}
